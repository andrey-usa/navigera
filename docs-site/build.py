#!/usr/bin/env python3
"""Write the docs site's pages from their one source each, then `mdbook build`.

    python3 docs-site/build.py [path/to/navigera]

Every page under docs-site/src except SUMMARY.md is generated, so the site
never drifts from what it shows:

    index.md        README.md up to its Benchmarks section
    benchmarks.md   README.md's Benchmarks and Agent eval sections
    reference.md    docs/navigera.md
    multi-model.md  docs/multi-model.md
    skill.md        skills/navigera/SKILL.md (without its front matter)
    commands.md     `navigera --help` of the binary given (default
                    target/release/navigera)

Relative links to a file that has a page become links to that page; links to
any other file in the repository point at it on GitHub. Standard library only.
"""
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs-site" / "src"
BLOB = "https://github.com/andrey-usa/navigera/blob/master/"
PAGES = {
    "README.md": "index.md",
    "docs/navigera.md": "reference.md",
    "docs/multi-model.md": "multi-model.md",
    "skills/navigera/SKILL.md": "skill.md",
}
LINK = re.compile(r"\]\((?!https?:|mailto:|#)([^)\s]+)\)")
GENERATED_NOTE = "<!-- Generated by docs-site/build.py from {src}. Edit the source, not this page. -->\n\n"


def relink(text, source):
    """Point a page's relative links at site pages or at GitHub."""
    base = pathlib.PurePosixPath(source).parent

    def fix(m):
        target, _, anchor = m.group(1).partition("#")
        path = pathlib.PurePosixPath(*(base / target).parts)
        parts = []
        for part in path.parts:
            if part == "..":
                if parts:
                    parts.pop()
            elif part != ".":
                parts.append(part)
        rel = "/".join(parts)
        page = PAGES.get(rel)
        url = page if page else BLOB + rel
        return f"]({url}{'#' + anchor if anchor else ''})"

    return LINK.sub(fix, text)


def section_split(readme):
    """README before `## Benchmarks`, and from there up to `## Contributing`."""
    start = readme.index("\n## Benchmarks")
    end = readme.index("\n## Contributing")
    return readme[:start] + readme[end:], readme[start:end]


def strip_front_matter(text):
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4)
        return text[end + 5 :].lstrip("\n")
    return text


def write(name, source, body):
    (SRC / name).write_text(GENERATED_NOTE.format(src=source) + body, encoding="utf-8")


def main():
    binary = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "target" / "release" / "navigera")
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    front, bench = section_split(readme)
    write("index.md", "README.md", relink(front, "README.md"))
    bench = bench.lstrip("\n").replace("## Benchmarks", "# Benchmarks and agent eval\n\n## Benchmarks", 1)
    write("benchmarks.md", "README.md", relink(bench, "README.md"))
    for source in ("docs/navigera.md", "docs/multi-model.md"):
        write(PAGES[source], source, relink((ROOT / source).read_text(encoding="utf-8"), source))
    skill = strip_front_matter((ROOT / "skills/navigera/SKILL.md").read_text(encoding="utf-8"))
    write("skill.md", "skills/navigera/SKILL.md", relink(skill, "skills/navigera/SKILL.md"))
    help_text = subprocess.run([str(binary), "--help"], check=True, capture_output=True, text=True).stdout
    write(
        "commands.md",
        f"`{binary.name} --help`",
        "# Command list (`navigera --help`)\n\nThe output of `navigera --help` from the build this site was made with:\n\n"
        f"```text\n{help_text.rstrip()}\n```\n",
    )
    print(f"docs-site: wrote 6 pages from {binary.name} {help_text.split(':', 1)[0].split()[-1]}")


if __name__ == "__main__":
    main()
