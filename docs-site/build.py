#!/usr/bin/env python3
"""Build the docs site from its sources. The same file in every product.

    python3 docs-site/build.py [--binary PATH | --no-binary] [--mdbook PATH] [--write | --check]

docs-site/site.toml lists the site's parts and, for each page, where its
text comes from: a whole file (docs/*.md, CHANGELOG.md, the skill), some
`## ` sections of one (README.md), or the output of the product's binary.
Every file under docs-site/src is written from those sources on each build,
so the site never says something its sources don't; nothing there is edited
by hand.

The build also writes SUMMARY.md, the index page, llms.txt (one line per
page, for agents), llms-full.txt (every page in one file) and the README's
`## Documentation` section. It stops, saying where, when a link points at a
file or a heading that does not exist, when a section of a source is on no
page, or when llms.txt outgrows its budget.

  --binary PATH  the built binary whose output `run` pages show (default
                 target/release/<binary>); --no-binary leaves a placeholder
                 there and checks everything else
  --mdbook PATH  then run `mdbook build`, put each page's markdown beside
                 its HTML, and check every internal link against the HTML
  --write        also rewrite README.md's Documentation section and llms.txt
  --check        fail if README.md's Documentation section or llms.txt
                 differs from what the build writes (CI)

Standard library only; Python 3.11 or newer (tomllib).
"""
import argparse
import html
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = ROOT / "docs-site"
SRC = SITE / "src"
BOOK = SITE / "book"
NOTE = "<!-- Generated by docs-site/build.py from {src}. Edit the source, not this page. -->"
README_NOTE = "<!-- Written by docs-site/build.py from docs-site/site.toml: edit that, then run it with --write. -->"
LLMS_MAX = 6000
PAGE_WORDS_MAX = 1500

HEADING = re.compile(r"^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$")
FENCE = re.compile(r"^[ \t]{0,3}(`{3,}|~{3,})")
INLINE_LINK = re.compile(r"(!?)\[((?:[^\]\\]|\\.)*)\]\(<?([^)\s>]+)>?((?:\s+\"[^\"]*\")?)\)")
REF_DEF = re.compile(r"^([ \t]{0,3}\[[^\]]+\]:[ \t]*)<?(\S+?)>?(\s.*)?$")
HTML_ATTR = re.compile(r"""(\s(href|src)=)(["'])([^"']+)\3""")
INCLUDE = re.compile(r"\{\{#(include|rustdoc_include)\s+([^}\s:]+)([^}]*)\}\}")
CODE_SPAN = re.compile(r"(`+)(?:(?!\1).)+?\1")
SCHEME = re.compile(r"^(?:[a-z][a-z0-9+.-]*:|//)", re.I)


class BuildError(Exception):
    pass


def fail(msg):
    raise BuildError(msg)


# ------------------------------------------------------------------ markdown


def code_flags(lines):
    """For each line, whether it is part of a fenced code block (its fences included)."""
    flags, fence = [], None
    for line in lines:
        m = FENCE.match(line)
        if fence is None:
            flags.append(bool(m))
            if m:
                fence = m.group(1)
        else:
            flags.append(True)
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and line.strip() == m.group(1):
                fence = None
    return flags


def heading_text(raw):
    """A heading as a reader sees it: no markup, links reduced to their text."""
    text = re.sub(r"!?\[((?:[^\]\\]|\\.)*)\]\([^)]*\)", r"\1", raw)
    text = re.sub(r"<[^>]+>", "", text).replace("`", "")
    text = re.sub(r"(\*\*|__)(.+?)\1", r"\2", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\1", text)
    return html.unescape(text).strip()


def slug(text):
    """A heading's id as mdBook makes it (and GitHub, for the headings these docs use)."""
    out = []
    for ch in text:
        if ch.isalnum() or ch in "-_":
            out.append(ch.lower() if ch.isascii() else ch)
        elif ch.isspace():
            out.append("-")
    return "".join(out)


class Ids:
    """Heading ids in document order, with the -1, -2 suffixes mdBook and GitHub add."""

    def __init__(self):
        self.seen = {}

    def __call__(self, text):
        base = slug(text)
        n = self.seen.get(base, 0)
        self.seen[base] = n + 1
        return base if n == 0 else f"{base}-{n}"


class Source:
    """One markdown file of the repository and its `## ` sections."""

    def __init__(self, rel):
        self.rel = rel
        path = ROOT / rel
        if not path.is_file():
            fail(f"site.toml: source {rel} does not exist")
        text = path.read_text(encoding="utf-8")
        if text.startswith("---\n"):  # a skill's front matter
            end = text.find("\n---\n", 4)
            if end > 0:
                text = text[end + 5:].lstrip("\n")
        self.lines = text.rstrip("\n").split("\n")
        self.code = code_flags(self.lines)
        ids = Ids()
        self.headings = {}  # line -> (level, text, id in this file)
        for i, line in enumerate(self.lines):
            m = None if self.code[i] else HEADING.match(line)
            if m:
                t = heading_text(m.group(2))
                self.headings[i] = (len(m.group(1)), t, ids(t))
        self.ids = {h[2] for h in self.headings.values()}
        tops = [i for i, h in self.headings.items() if h[0] <= 2]
        self.sections, self.order = {}, []
        for i in tops:
            if self.headings[i][0] != 2:
                continue
            name = self.headings[i][1]
            if name in self.sections:
                fail(f"{rel}: two sections named '{name}'; site.toml can't tell them apart")
            self.sections[name] = (i, next((j for j in tops if j > i), len(self.lines)))
            self.order.append(name)
        first = min((s for s, _ in self.sections.values()), default=len(self.lines))
        start = 1 if self.headings.get(0, (0,))[0] == 1 else 0
        self.preamble = (start, first)

    def section(self, name):
        if name not in self.sections:
            have = ", ".join(f"'{s}'" for s in self.order) or "none"
            fail(f"site.toml: {self.rel} has no section '{name}' (it has {have})")
        return self.sections[name]

    def preamble_has_text(self):
        a, b = self.preamble
        return any(x.strip() for x in self.lines[a:b])


# ------------------------------------------------------------------ pages


class Line:
    __slots__ = ("text", "code", "src", "src_id")

    def __init__(self, text, code=False, src=None, src_id=None):
        self.text, self.code, self.src, self.src_id = text, code, src, src_id


class Page:
    def __init__(self, path, title, about, part):
        self.path, self.title, self.about, self.part = path, title, about, part
        self.lines = []  # [Line]
        self.files = []  # what the page is made from, for its note and footer
        self.tops = []  # (file, id) of headings the page title stands for
        self.ids = set()
        self.long = False

    @property
    def dir(self):
        return pathlib.PurePosixPath(self.path).parent


def take(page, src, start, end, drop_first, demote=False):
    """Copy lines [start, end) of a source onto a page.

    drop_first: the first heading is the page's title, so it goes and the
    rest move up a level. demote: every heading moves down a level, so a
    whole file's title becomes one `## ` section of a page holding several."""
    shift = -1 if drop_first else (1 if demote else 0)
    for i in range(start, end):
        h = src.headings.get(i)
        if h and drop_first and i == start:
            page.tops.append((src.rel, h[2]))
            continue
        text = src.lines[i]
        if h:
            m = HEADING.match(text)
            text = "#" * min(6, max(2, h[0] + shift)) + " " + m.group(2)
            page.lines.append(Line(text, False, src.rel, h[2]))
        else:
            page.lines.append(Line(text, src.code[i], src.rel))
    page.lines.append(Line(""))


def run_binary(binary, args):
    if binary is None:
        return f"(not built here: docs-site/build.py --binary PATH shows `{' '.join(args)}`)"
    try:
        p = subprocess.run([str(binary), *args], capture_output=True, text=True, timeout=60)
    except FileNotFoundError:
        fail(f"{binary} not found: build it (cargo build --release), pass --binary PATH, or --no-binary")
    if p.returncode != 0:
        fail(f"`{binary.name} {' '.join(args)}` exited {p.returncode}: {p.stderr.strip()[:300]}")
    return p.stdout.rstrip()


def build_pages(cfg, binary, sources):
    """The index first, then every page site.toml lists, assembled from their sources."""

    def get(rel):
        if rel not in sources:
            sources[rel] = Source(rel)
        return sources[rel]

    used = {}
    readme = get("README.md")
    index = Page("index.md", cfg["name"], "", None)
    index.files.append("README.md")
    index.tops.append(("README.md", readme.headings[0][2]) if 0 in readme.headings else ("README.md", ""))
    take(index, readme, *readme.preamble, False)
    used["README.md"] = {"_preamble"}
    pages = [index]
    for part in cfg["part"]:
        for pc in part.get("page", []):
            for key in ("title", "path", "about", "source"):
                if key not in pc:
                    fail(f"site.toml: a page in '{part['title']}' has no `{key}`")
            if not pc["path"].endswith(".md") or any(p.path == pc["path"] for p in pages):
                fail(f"site.toml: page path {pc['path']} is not a new .md path")
            page = Page(pc["path"], pc["title"], " ".join(pc["about"].split()), part["title"])
            page.long = pc.get("long", False)  # a changelog: long by nature, read by search
            specs = pc["source"] if isinstance(pc["source"], list) else [pc["source"]]
            for n, spec in enumerate(specs):
                if "intro" in spec:
                    page.lines += [Line(x) for x in spec["intro"].strip().split("\n")] + [Line("")]
                if "run" in spec:
                    cmd = " ".join([cfg["binary"], *spec["run"]])
                    out = run_binary(binary, spec["run"])
                    page.lines += [Line("```text", True), Line(f"$ {cmd}", True)]
                    page.lines += [Line(x, True) for x in out.split("\n")] + [Line("```", True), Line("")]
                    page.files.append(f"`{cmd}`")
                    continue
                if "file" not in spec:
                    if "intro" not in spec:
                        fail(f"site.toml: page {page.path}: a source needs `file`, `run` or `intro`")
                    continue
                src = get(spec["file"])
                if src.rel not in page.files:
                    page.files.append(src.rel)
                names = spec.get("sections") or ([spec["section"]] if "section" in spec else [])
                mine = used.setdefault(src.rel, set())
                if spec.get("preamble"):
                    take(page, src, *src.preamble, False)
                    mine.add("_preamble")
                for name in names:
                    a, b = src.section(name)
                    lead = n == 0 and len(names) == 1 and not spec.get("preamble") and not spec.get("keep_heading")
                    take(page, src, a, b, lead)
                    mine.add(name)
                if not names and not spec.get("preamble"):
                    if spec.get("demote"):
                        take(page, src, 0, len(src.lines), False, demote=True)
                    else:
                        if 0 in src.headings and src.headings[0][0] == 1:
                            page.tops.append((src.rel, src.headings[0][2]))
                        take(page, src, src.preamble[0], len(src.lines), False)
                    mine.update(["_preamble", *src.order])
            pages.append(page)

    # Every section of every file a page draws on is on some page.
    ignore = cfg.get("coverage", {}).get("ignore", {})
    for rel, names in used.items():
        src = sources[rel]
        wanted = (["_preamble"] if src.preamble_has_text() else []) + src.order
        missing = [s for s in wanted if s not in names and s not in ignore.get(rel, [])]
        if missing:
            fail(f"{rel}: on no page of the site: " + ", ".join(f"'{m}'" for m in missing)
                 + " (place it in site.toml, or list it under [coverage.ignore])")
    return pages


def assign_ids(pages):
    """Each page's heading ids as mdBook makes them, and where each source heading landed."""
    where, first_page = {}, {}
    for page in pages:
        ids = Ids()
        page.ids.add(ids(page.title))
        for rel, sid in page.tops:
            where.setdefault((rel, sid), (page, None))
        for line in page.lines:
            if line.src:
                first_page.setdefault(line.src, page)
            if line.src_id is not None:
                fid = ids(heading_text(HEADING.match(line.text).group(2)))
                page.ids.add(fid)
                where.setdefault((line.src, line.src_id), (page, fid))
    return where, first_page


# ------------------------------------------------------------------ links


def relpath(target, from_dir):
    return os.path.relpath(str(target), str(from_dir)).replace(os.sep, "/")


SELF = "\x01self\x01"  # a link to the page it is on


def drop_self_links(lines):
    """A sentence whose link points at the page it is on (a README line sending
    the reader to the page that now holds the rest) is left out of that page;
    in a list or a table only the link goes, its text stays."""
    out, para = [], []

    def flush():
        if not para:
            return
        text = "\n".join(para)
        if SELF in text:
            if re.match(r"\s*([-*+] |\d+\. |\|)", para[0]):
                text = re.sub(r"\[((?:[^\]\\]|\\.)*)\]\(" + SELF + r"[^)]*\)", r"\1", text)
            else:
                sentences = re.split(r"(?<=[.!?])\s+(?=[A-Z`*\[(])", " ".join(text.split()))
                text = " ".join(x for x in sentences if SELF not in x)
        if text.strip():
            out.append(text)
        para.clear()

    for line, code in lines:
        if code or not line.strip() or HEADING.match(line):
            flush()
            out.append(line)
        else:
            para.append(line)
    flush()
    return out


class Linker:
    def __init__(self, cfg, pages, sources):
        self.cfg, self.sources, self.pages = cfg, sources, pages
        self.where, self.first_page = assign_ids(pages)

    def resolve(self, page, src_rel, target, image):
        """Where a link written in src_rel points from the page it landed on."""
        url = site_url(self.cfg)
        if target.startswith(url):  # a page of this site, written as its public URL
            path, _, anchor = target[len(url):].partition("#")
            stem = re.sub(r"\.(html|md)$", "", path)
            dest = next((p for p in self.pages if p.path[:-3] == stem or (p.path == "index.md" and stem in ("", "index"))), None)
            if dest is None:
                return relpath(path or "index.md", page.dir) if path.endswith(".txt") else target
            if dest is page and not anchor:
                return SELF
            return ("" if dest is page else relpath(dest.path, page.dir)) + (f"#{anchor}" if anchor else "")
        if SCHEME.match(target):
            return target
        path, _, anchor = target.partition("#")
        rel = src_rel
        if path:
            parts = []
            for p in (pathlib.PurePosixPath(src_rel).parent / path).parts:
                if p == "..":
                    if not parts:
                        fail(f"{src_rel}: link {target} leaves the repository")
                    parts.pop()
                elif p != ".":
                    parts.append(p)
            rel = "/".join(parts)
        if rel == "llms.txt" and not anchor:  # the repository's copy of the site's own
            return relpath("llms.txt", page.dir)
        if not image and rel in self.sources:
            if anchor:
                hit = self.where.get((rel, anchor))
                if hit is None:
                    why = "is on no page" if anchor in self.sources[rel].ids else "does not exist"
                    fail(f"{src_rel}: link {target}: the heading #{anchor} of {rel} {why}")
                dest, fid = hit
            else:
                dest, fid = self.first_page.get(rel), None
                if dest is None:
                    fail(f"{src_rel}: link {target}: {rel} is on no page")
            if dest is page and not fid:
                return SELF
            url = "" if dest is page else relpath(dest.path, page.dir)
            return f"{url}#{fid}" if fid else url
        full = ROOT / rel
        if not full.exists():
            fail(f"{src_rel}: link {target}: {rel} does not exist")
        repo, branch = self.cfg["repo"], self.cfg["branch"]
        if image:
            return f"https://raw.githubusercontent.com/{repo}/{branch}/{rel}"
        kind = "tree" if full.is_dir() else "blob"
        return f"https://github.com/{repo}/{kind}/{branch}/{rel}" + (f"#{anchor}" if anchor else "")

    def links(self, page, src, text):
        """Every link of one paragraph (it may wrap over lines) pointed where it lands."""
        spans = []

        def mask(m):
            spans.append(m.group(0))
            return f"\x00{len(spans) - 1}\x00"

        text = CODE_SPAN.sub(mask, text)
        text = INLINE_LINK.sub(lambda m: "{}[{}]({}{})".format(
            m.group(1), m.group(2), self.resolve(page, src, m.group(3), bool(m.group(1))), m.group(4)), text)
        text = "\n".join(
            (rd.group(1) + self.resolve(page, src, rd.group(2), False) + (rd.group(3) or "")) if rd else line
            for line, rd in ((x, REF_DEF.match(x)) for x in text.split("\n")))
        text = HTML_ATTR.sub(lambda m: m.group(1) + m.group(3) + self.resolve(
            page, src, m.group(4), m.group(2) == "src") + m.group(3), text)
        return re.sub("\x00(\\d+)\x00", lambda m: spans[int(m.group(1))], text)

    def text(self, page):
        out, para = [], []

        def flush():
            if para:
                text = "\n".join(x.text for x in para)
                out.append((self.links(page, para[0].src, text), False))
                para.clear()

        for line in page.lines:
            if line.src is None or line.code or not line.text.strip() or line.src_id is not None:
                flush()
                if line.src is None:
                    out.append((line.text, line.code))
                elif line.code:
                    out.append((INCLUDE.sub(lambda m: include_path(m, line.src, page), line.text), True))
                else:
                    out.append((self.links(page, line.src, line.text), False))
                continue
            if para and para[0].src != line.src:
                flush()
            para.append(Line(INCLUDE.sub(lambda m: include_path(m, line.src, page), line.text), False, line.src))
        flush()
        return "\n".join(drop_self_links(out)).strip("\n")


def include_path(m, src_rel, page):
    """An mdBook include written relative to its source, made relative to the page under src/."""
    target = pathlib.PurePosixPath(src_rel).parent / m.group(2)
    if not (ROOT / target).exists():
        fail(f"{src_rel}: {{{{#{m.group(1)} {m.group(2)}}}}}: {target} does not exist")
    return "{{#" + m.group(1) + " " + relpath(target, pathlib.PurePosixPath("docs-site/src") / page.dir) + m.group(3) + "}}"


# ------------------------------------------------------------------ output


def first_sentence(text):
    m = re.match(r"(.+?[.!?])(\s|$)", " ".join(text.split()))
    return m.group(1) if m else text.strip()


def site_url(cfg):
    return cfg.get("site", f"https://{cfg['repo'].split('/')[0]}.github.io/{cfg['name']}/")


def git(*args):
    p = subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True)
    return p.stdout.strip() if p.returncode == 0 else ""


def build_line(cfg, binary, pages):
    """What the site was built from: the commit, and what the binary says it is."""
    version = run_binary(binary, ["--version"]).splitlines()[0] if binary else ""
    if not version:
        m = re.search(r'(?m)^version\s*=\s*"([^"]+)"', (ROOT / "Cargo.toml").read_text(encoding="utf-8"))
        version = f"{cfg['name']} {m.group(1)}" if m else cfg["name"]
    commit, date = git("rev-parse", "--short=7", "HEAD"), git("log", "-1", "--format=%cs")
    m = re.match(r"(v[\d.]+)-(\d+)-g", git("describe", "--tags", "--match", "v*"))
    ahead = f", {m.group(2)} commits after {m.group(1)}" if m else ""
    if not commit:
        return f"Built from an uncommitted tree; `{cfg['binary']} --version` says `{version}`."
    link = f"[{commit}](https://github.com/{cfg['repo']}/commit/{commit})"
    line = f"Built from commit {link}{ahead}, of {date}; `{cfg['binary']} --version` says `{version}`."
    if m:
        log = next((p for p in pages if "CHANGELOG.md" in p.files), None)
        what = f"[changelog]({log.path}#unreleased)" if log else "changelog"
        tag = m.group(1).lstrip("v")
        line += (f" These docs are ahead of the {tag} release: what the {what} lists under"
                 f" Unreleased is not in {tag} yet.")
    return line


def contents(cfg, pages, base, ext, about):
    out = []
    for part in cfg["part"]:
        mine = [p for p in pages if p.part == part["title"]]
        if about:
            out += [f"## {part['title']}", ""]
            out += [f"- [{p.title}]({base}{p.path[:-3]}{ext}): {first_sentence(p.about)}" for p in mine]
            out.append("")
        else:
            out.append(f"- **{part['title']}:** " + " · ".join(f"[{p.title}]({base}{p.path[:-3]}{ext})" for p in mine))
    return out


def llms_txt(cfg, pages):
    url = site_url(cfg)
    head = [f"# {cfg['name']}", "", f"> {' '.join(cfg['summary'].split())}", "",
            f"Each page below is markdown. The whole site in one file: {url}llms-full.txt", ""]
    return "\n".join(head + contents(cfg, pages[1:], url, ".md", True)).rstrip("\n") + "\n"


def readme_section(cfg, pages):
    url = site_url(cfg)
    return "\n".join(["## Documentation", "", README_NOTE, "",
                      f"The docs site, {url}, has the same parts for every tool:", ""]
                     + contents(cfg, pages[1:], url, ".html", False)
                     + ["", f"For agents: [llms.txt]({url}llms.txt) lists every page as markdown, and "
                            f"[llms-full.txt]({url}llms-full.txt) is the whole site in one file.", ""])


def splice_readme(text, section):
    m = re.search(r"(?m)^## Documentation[ \t]*$", text)
    if not m:
        fail("README.md has no `## Documentation` heading for the build to write under")
    rest = re.search(r"(?m)^## ", text[m.end():])
    end = m.end() + rest.start() if rest else len(text)
    return text[:m.start()] + section + ("\n" if rest else "") + text[end:]


def write_site(cfg, pages, linker, binary):
    if SRC.exists():
        shutil.rmtree(SRC)
    SRC.mkdir(parents=True)
    long_pages, written = [], {}
    for page in pages:
        body = re.sub(r"\n{3,}", "\n\n", linker.text(page))
        if page.path == "index.md":
            text = (NOTE.format(src="README.md and docs-site/site.toml") + f"\n\n# {cfg['name']}\n\n{body}\n\n"
                    + "\n".join(contents(cfg, pages[1:], "", ".md", True)) + f"\n{build_line(cfg, binary, pages)}\n")
        else:
            made_of = ", ".join(f if f.startswith("`") else
                                f"[{f}](https://github.com/{cfg['repo']}/blob/{cfg['branch']}/{f})" for f in page.files)
            text = (NOTE.format(src=", ".join(page.files)) + f"\n\n# {page.title}\n\n{page.about}\n\n{body}\n\n"
                    f"---\n\n<small>Made from {made_of}.</small>\n")
            words = len(re.findall(r"\S+", body))
            if words > PAGE_WORDS_MAX and not page.long:
                long_pages.append(f"{page.path}: {words} words")
        out = SRC / page.path
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        written[page.path] = text
    summary = ["# Summary", "", f"[{cfg['name']}](index.md)", ""]
    for part in cfg["part"]:
        summary += [f"# {part['title']}", ""] + [f"- [{p.title}]({p.path})" for p in pages if p.part == part["title"]] + [""]
    (SRC / "SUMMARY.md").write_text("\n".join(summary), encoding="utf-8")
    llms = llms_txt(cfg, pages)
    if len(llms.encode()) > LLMS_MAX:
        fail(f"llms.txt would be {len(llms.encode())} bytes, over {LLMS_MAX}: shorten the pages' `about`")
    (SRC / "llms.txt").write_text(llms, encoding="utf-8")
    full = "\n\n".join([f"# {cfg['name']}: the whole documentation", f"> {' '.join(cfg['summary'].split())}",
                        f"Pages in site order; each is also at {site_url(cfg)}<page>.md."] + list(written.values()))
    (SRC / "llms-full.txt").write_text(full, encoding="utf-8")
    return llms, len(full.encode()), long_pages


def check_html():
    """Every internal link of every built page resolves to a file and, with #id, to an id in it."""
    ids_of, bad, n = {}, [], 0
    for f in sorted(BOOK.rglob("*.html")):
        if f.name in ("print.html", "404.html", "toc.html"):
            continue
        n += 1
        text = f.read_text(encoding="utf-8", errors="replace")
        main = text.split("<main>", 1)[-1].split("</main>", 1)[0]
        for href in re.findall(r'href="([^"]+)"', main):
            if SCHEME.match(href):
                continue
            path, _, anchor = html.unescape(href).partition("#")
            target = (f.parent / path).resolve() if path else f
            if not target.exists():
                bad.append(f"{f.relative_to(BOOK)}: {href}: no such file")
                continue
            if anchor and target.suffix == ".html":
                if target not in ids_of:
                    ids_of[target] = set(re.findall(r'\sid="([^"]+)"', target.read_text(encoding="utf-8", errors="replace")))
                if anchor not in ids_of[target]:
                    bad.append(f"{f.relative_to(BOOK)}: {href}: no id '{anchor}' there")
    if bad:
        fail("broken links in the built site:\n  " + "\n  ".join(bad[:40]))
    return n


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--binary")
    ap.add_argument("--no-binary", action="store_true")
    ap.add_argument("--mdbook")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not (SITE / "site.toml").exists():
        fail(f"no {SITE / 'site.toml'}: it lists the site's parts and pages (see another tool's for the shape)")
    try:
        cfg = tomllib.loads((SITE / "site.toml").read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as e:
        fail(f"docs-site/site.toml: {e}")
    for key in ("name", "repo", "branch", "binary", "summary", "part"):
        if key not in cfg:
            fail(f"site.toml has no `{key}`")
    binary = None if a.no_binary else pathlib.Path(a.binary or ROOT / "target" / "release" / cfg["binary"])
    if binary is not None and not binary.exists():
        fail(f"{binary} not found: build it (cargo build --release), pass --binary PATH, or --no-binary")

    sources = {}
    pages = build_pages(cfg, binary, sources)
    linker = Linker(cfg, pages, sources)
    llms, full_bytes, long_pages = write_site(cfg, pages, linker, binary)

    readme_path, llms_path = ROOT / "README.md", ROOT / "llms.txt"
    readme = readme_path.read_text(encoding="utf-8")
    url = site_url(cfg)
    known = {p.path[:-3] for p in pages} | {"llms", "llms-full", ""}
    for link in re.findall(r"\]\((" + re.escape(url) + r"[^)\s]*)\)", readme):
        path, _, anchor = link[len(url):].partition("#")
        stem = re.sub(r"\.(html|md|txt)$", "", path)
        if stem.endswith("/index") or stem == "index":
            stem = stem[:-5].rstrip("/")
        if stem not in known:
            fail(f"README.md links {link}, a page the site does not have (pages: site.toml)")
        if anchor:
            page = next((p for p in pages if p.path[:-3] == stem), None)
            if page is not None and anchor not in page.ids:
                fail(f"README.md links {link}: that page has no heading with id '{anchor}'")
    new_readme = splice_readme(readme, readme_section(cfg, pages))
    stale = [name for name, ok in (("README.md's Documentation section", new_readme == readme),
                                   ("llms.txt", llms_path.exists() and llms_path.read_text(encoding="utf-8") == llms))
             if not ok]
    if a.write:
        readme_path.write_text(new_readme, encoding="utf-8")
        llms_path.write_text(llms, encoding="utf-8")
    elif a.check and stale:
        fail(" and ".join(stale) + " differ from what the build writes: run docs-site/build.py --write and commit")

    built = ""
    if a.mdbook:
        if BOOK.exists():
            shutil.rmtree(BOOK)
        p = subprocess.run([a.mdbook, "build", str(SITE)], capture_output=True, text=True)
        if p.returncode != 0:
            fail(f"mdbook build failed:\n{p.stderr[-3000:]}")
        for page in pages:
            (BOOK / page.path).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(SRC / page.path, BOOK / page.path)
        built = f"; {check_html()} HTML pages, every internal link and id resolves"
    print(f"docs-site: {len(pages)} pages from {len(sources)} sources in {len(cfg['part'])} parts; "
          f"llms.txt {len(llms.encode())} B, llms-full.txt {full_bytes} B (about {full_bytes // 4} tokens){built}")
    for w in long_pages:
        print(f"docs-site: warning: {w}, over {PAGE_WORDS_MAX}: split it by task")
    if stale and not a.write:
        print("docs-site: " + " and ".join(stale) + " differ from what the build writes (--write updates them)")


if __name__ == "__main__":
    try:
        main()
    except BuildError as e:
        sys.exit(f"docs-site: {e}")
